export interface DemoCatalogSummary {
  total: number;
  premium: number;
  free: number;
  delivery: number;
  sandwich: number;
  withPhone: number;
  withHours: number;
  allTagged: boolean;
}

export function summarizeDemoCatalog(pois: ChartronsPoiInput[] = DEMO_CHARTRONS_POIS): DemoCatalogSummary {
  const hay = (poi: ChartronsPoiInput) => `${poi.name} ${poi.specialty} ${poi.description}`.toLowerCase();
  const premium = pois.filter((poi) => poi.tier === 'premium_pro').length;
  return {
    total: pois.length,
    premium,
    free: pois.length - premium,
    delivery: pois.filter((poi) => poi.hasDelivery).length,
    sandwich: pois.filter((poi) => hay(poi).includes('sandwich')).length,
    withPhone: pois.filter((poi) => Boolean(poi.phone)).length,
    withHours: pois.filter((poi) => Boolean(poi.openingHours)).length,
    allTagged: pois.every((poi) => poi.isDemo === true && poi.id.startsWith(DEMO_POI_ID_PREFIX)),
  };
}

