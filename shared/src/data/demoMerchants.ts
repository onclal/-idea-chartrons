export function assertDemoCatalogReady(pois: ChartronsPoiInput[] = DEMO_CHARTRONS_POIS): DemoCatalogSummary {
  const summary = summarizeDemoCatalog(pois);
  if (!summary.allTagged) {
    throw new Error('Demo catalog hygiene failed: every record must set isDemo: true and a demo- id prefix.');
  }
  if (summary.total < 10) {
    throw new Error(`Demo catalog too small (${summary.total}).`);
  }
  const premiumRatio = summary.premium / summary.total;
  if (premiumRatio < 0.4 || premiumRatio > 0.6) {
    throw new Error(`Expected ~50% Premium Pro, got ${summary.premium}/${summary.total}.`);
  }
  if (summary.sandwich < 2 || summary.delivery < 3) {
    throw new Error('Demo catalog must include sandwich shops with delivery for concierge queries.');
  }
  return summary;
}
